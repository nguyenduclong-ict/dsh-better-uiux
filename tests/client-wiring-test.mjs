// Wiring-contract test for dsh-better-uiux.
//
// What CAN be checked without a browser is the contract between the pieces: the
// module ids the loader will see, the slot names the shell will fill, and the
// exact fork semantics the message editor relies on. This test asserts those
// against the shipped sources, so a refactor that silently breaks the wiring
// fails here instead of in the GUI.
//
// It is deliberately NOT a substitute for opening Settings in the real GUI — see
// README "Verify" for the manual checklist.
//
// Usage:  node tests/client-wiring-test.mjs

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pluginDir = join(dirname(fileURLToPath(import.meta.url)), '..');

let failures = 0;
let checks = 0;

function check(label, condition, detail) {
  checks += 1;
  if (condition) {
    console.log(`  ok    ${label}`);
  } else {
    failures += 1;
    console.error(`  FAIL  ${label}${detail === undefined ? '' : ` — ${detail}`}`);
  }
}

const section = (title) => console.log(`\n${title}`);
const read = (file) => readFileSync(join(pluginDir, file), 'utf-8');

const core = read('client.js');
const coreSource = read('core.js');
const liveSource = read('live-terminal.js');
const live = liveSource;
const host = read('index.js');
const pkg = JSON.parse(read('package.json'));

console.log('dsh-better-uiux wiring contract');

section('1. package declares one client bundle and one host patch');
check('main entry is index.js', pkg.main === './index.js', pkg.main);
check('client subpath is exported', pkg.exports['./client'] === './client.js', pkg.exports['./client']);
check('dsh.client.platform is web', pkg.dsh.client.platform === 'web');
check('client bundle injects the settings package', pkg.dsh.client.inject.includes('@deepseek-ai/dsh-client-ui-settings'), pkg.dsh.client.inject.join(', '));
check('client bundle injects the locale package', pkg.dsh.client.inject.includes('@deepseek-ai/dsh-client-locale'));
check('bundle patch is declared', pkg.dsh.bundle.patch === './cordis.patch.yml');

section('2. the served bundle is ONE module with the live half inlined');
check('core module id', coreSource.includes(`id: 'dsh-better-uiux',`));
check('live source still registers its own id (readable in isolation)', liveSource.includes(`id: 'dsh-better-uiux/live-terminal',`));
check('one source file per part',
  (coreSource.match(/__ModuleLoader__\.load\(/g) ?? []).length === 1
    && (liveSource.match(/__ModuleLoader__\.load\(/g) ?? []).length === 1);
// THE BUG THIS GUARDS: the bundle used to register TWO modules, and the shell only
// runs apply() for a package's PRIMARY module. The live half therefore loaded and
// never started — no style tag, no buttons — while the host half streamed output
// perfectly. Registering one module is what makes the live half actually run.
check('the served bundle registers exactly ONE module',
  (core.match(/__ModuleLoader__\.load\(/g) ?? []).length === 1,
  `server sees ${(core.match(/__ModuleLoader__\.load\(/g) ?? []).length} registration(s)`);
check('the second module id is not registered by the bundle',
  !core.includes("id: 'dsh-better-uiux/live-terminal'"));
check('the live half is inlined into the core factory', core.includes('const liveTerminalModule = (() => {'));
check('the live half is exposed for apply()', core.includes('exports.__liveTerminal = liveTerminalModule;'));
check('apply() starts the live half', core.includes('exports.__liveTerminal.apply(ctx);'));
check('the served bundle is the generated artifact',
  /GENERATED by build\.mjs/.test(core));

section('3. the Settings section is "Better UIUX" with the full item surface');
check('core fills settings.section', core.includes(`const SECTION_SLOT = 'settings.section';`));
check('section id is better-uiux', /id: 'better-uiux',/.test(core));
check('section label comes from the dictionary', /label: \(\) => t\('nav'\),/.test(core));
check('nav string is "Better UIUX"', /nav: 'Better UIUX'/.test(core));
check('section declares no child slot (it renders everything itself)', !/children:/.test(coreSource.slice(coreSource.indexOf('function apply'), coreSource.indexOf('function apply') + 900)));
check('order sits after general(0) and custom-css(40)', /order: 41,/.test(core));

section('4. every feature has a switch and a hint in all three locales');
for (const key of ['liveTerminal', 'customCss', 'editMessage']) {
  const zh = new RegExp(`${key}Label:`).test(core);
  const count = (core.match(new RegExp(`${key}Hint:`, 'g')) ?? []).length;
  check(`${key}: label + 3 hints`, zh && count === 3, `hints=${count}`);
}
check('three locales registered', /ctx\.locale\.register\(NS, \{ zh, en, vi \}\)/.test(core));
// Edit message is temporarily hidden: the switch list must drop it while the
// constant stays the single place that brings it back.
check('the hidden-feature constant exists', /const EDIT_MESSAGE_HIDDEN = true;/.test(core));
check(
  'feature keys enumerate the two visible switches while edit stays hidden',
  /const FEATURE_KEYS = EDIT_MESSAGE_HIDDEN\s*\? \['liveTerminal', 'customCss'\]\s*: \['liveTerminal', 'customCss', 'editMessage'\];/.test(core)
);
check('the editor never starts while hidden', /if \(!EDIT_MESSAGE_HIDDEN && config\.features\.editMessage === true\) \{/.test(core));
check('no switch row is rendered for the hidden feature', !/onToggle: \(\) => toggle\('editMessage'\)/.test(core));
check('custom CSS switch is NOT a separate page (requirement)', !/id: 'custom-css'/.test(core));

section('5. the live-terminal module is gated by the shared switch');
check('reads the shared hand-off object', live.includes(`const GLOBAL_KEY = '__DSH_BETTER_UIUX__';`));
check('same key on both sides', core.includes(`const GLOBAL_KEY = '__DSH_BETTER_UIUX__';`));
check('gate helper exists', /function isEnabled\(\)/.test(live));
check('switch read through featureOn("liveTerminal")', /core\.featureOn\('liveTerminal'\) === true/.test(live));
check('job-status poll is gated', /async function syncJobsStatus\(\) \{\n\s*if \(!isEnabled\(\)\) return;/.test(live));
check('transcript rescan is gated', /function updateLiveBlocks\(\) \{\n\s*if \(!isEnabled\(\)\) return;/.test(live));
check('MutationObserver callback is gated', /if \(!isEnabled\(\)\) return;\n\s*if \(isPerformingPluginDomUpdates\) return;/.test(live));
check('teardown removes injected blocks', live.includes(`'.dsh-live-terminal-block',`));
check('teardown removes the footer row', live.includes(`'.dsh-live-footer-row',`));
check('teardown removes the plugin stylesheet', /document\.getElementById\(STYLE_ID\)[\s\S]{0,40}\.remove\(\)/.test(live));
check('teardown unmounts the modal root', /__dshLiveTerminalRoot\.unmount/.test(live));
check('teardown reacts to the switch flipping off', /else if \(!next && liveActive\) \{\n\s*teardownLive\(\);/.test(live));
check('core pushes feature changes to subscribers', /onFeatures: \(listener\) => \{/.test(core));
check('live module subscribes', /core\.onFeatures\(\(features\) => \{/.test(live));

section('6. custom CSS honours its own switch');
check('injection requires the switch AND non-empty css', /const shouldInject = config\.features\.customCss && css\.trim\(\)\.length > 0;/.test(core));
check('style tag id is namespaced', core.includes(`const STYLE_ID = 'dsh-better-uiux-style';`));
check('tag re-appended so it wins the cascade', /if \(tag !== document\.head\.lastElementChild\) document\.head\.appendChild\(tag\);/.test(core));
check('host route used for persistence', core.includes(`fetch('/api/better-uiux/config'`));
check('localStorage mirror written', /window\.localStorage\.setItem\(CACHE_KEY/.test(core));

section('7. message editor: fork semantics are the load-bearing part');
/** Code only, comments stripped — prose must never satisfy or trip a check. */
const coreWithoutComments = core
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^\s*\/\/.*$/gm, '');
check('turn anchors come from the native turnTail slot', core.includes(`name: 'conversation.chat.turnTail',`));
check('probe records turn -> seq', /turnEndSeq\.set\(turn, seq\);/.test(core));
check('anchor map keyed by turn number', /const turnEndSeq = new Map\(\);/.test(core));
check(
  'forks at the turn BEFORE the edited one, never at the edited turn',
  /function resolveForkAnchor\(turn\) \{[\s\S]{0,220}?turnEndSeq\.get\(turn - 1\)/.test(core)
);
check(
  'a missing N-1 anchor falls back to the nearest turn below',
  /if \(knownTurn >= turn\) continue;/.test(core),
  'a too-late cut would leave the old text in the child'
);
check('fork carries sessionId + atSeq', /sessions\.fork\(\{ sessionId, atSeq: anchor, increaseTitle: true \}\)/.test(core));
check(
  'a missing anchor is reported with the anchor turn and the known anchors',
  /the turn anchor probe has not run/.test(core)
);
check('the anchor state is inspectable at runtime', /anchorState: \(\) => \(\{/.test(core));
check('it is published on a global for DevTools', /globalThis\[GLOBAL_KEY\] = exports\.__internals;/.test(core));
// That global is also the live-terminal half's contract, so the internals must
// carry the three things it reads, or the feature silently never gates.
check('the global keeps the live-terminal contract', /featureOn:/.test(core) && /onFeatures:/.test(core) && /whenHydrated:/.test(core));
// `ClientSessions.fork` RESOLVES TO THE CHILD ID STRING and throws on failure.
// Reading it as an `{ok, value}` envelope silently pushed every edit down the
// fallback path, i.e. into the current session's queue.
// Checked against `coreWithoutComments` so the doc comment that NAMES the old
// buggy shape is not mistaken for a regression.
check(
  'fork result is read as a child id string',
  /const childId = await sessions\.fork\(/.test(coreWithoutComments)
);
check(
  'fork result is NOT read as an {ok, value} envelope',
  !/forked\?\.ok === true/.test(coreWithoutComments) && !/\.value\?\.sessionId/.test(coreWithoutComments),
  'sessions.fork resolves to a string, not an envelope'
);
check('child is opened', /sessions\.open\(childId\);/.test(core));
check('child receives the rewritten text', /child\.prompt\(\[\{ type: 'text', text \}\], 'queue'\)/.test(core));
// NO SILENT FALLBACK. A failed branch must report and change nothing; appending
// is a deliberate choice via the composer button. Appending automatically is what
// made a failed edit look like "my message got added to the queue".
// Note: matching the bare name would also hit the helper's own DEFINITION, so the
// check targets a call site — `await resendInCurrentSession(`.
check(
  'a failed branch does NOT auto-append to the current session',
  !/await resendInCurrentSession\(/.test(coreWithoutComments),
  'the edit path must not append on failure'
);
check('the failure is reported with its real reason', /const reason = describeFailure\(error\);/.test(core));
check(
  'describeFailure prefers the rpc code and never returns empty',
  /function describeFailure\(error\) \{[\s\S]{0,700}?return String\(error\);/.test(core)
);
check('the append helper survives as an explicit escape hatch', /async function resendInCurrentSession\(/.test(core));
check('the retired fallback copy is gone from the dictionaries', !/editFallback/.test(coreSource));
check('edit buttons are namespaced for cleanup', core.includes(`const EDIT_HOST_CLASS = 'dsh-bu-edit-host';`));
check('cleanup removes every injected button', /querySelectorAll\(`\.\$\{EDIT_BTN_CLASS\}`\)/.test(core));
check('rows are matched on the real chat attributes', core.includes(`const USER_ROW_SELECTOR = '[data-chat-flow-kind="user"][data-chat-flow-key]';`));
check('turn number read from the row', /row\.getAttribute\('data-chat-turn'\)/.test(core));

section('7b. Edit button: glyph and placement contract');
// The glyph is DSH's own `IconEditOutline16` (`ic_ds_edit_outline_16`) copied
// verbatim from @deepseek-ai/dsh-client-ui-primitives, so the injected action is
// visually identical to the native actions beside it. It is a single FILLED path
// in a 16x16 box — not a stroked 24-box Lucide glyph, which is what it used to be.
check('uses the native edit icon path', coreSource.includes('M9.94076 1.34942C10.7047 0.90231'));
check('includes the native underline sub-path', coreSource.includes('15.5427 14.8398H7.55223'));
check('drawn in the native 16x16 box', /width="16" height="16" viewBox="0 0 16 16"/.test(coreSource));
check('fill-based, like every shell icon', /<path fill="currentColor" d="/.test(coreSource));
check(
  'no Lucide leftover (stroke icon or 24 box rescale)',
  !/stroke="currentColor" stroke-width="2"/.test(coreSource) && !/scale\(0\.6667\)/.test(coreSource)
);
check('icon is decorative (label lives on the button)', /aria-hidden="true" focusable="false"/.test(coreSource));
check('button has no text glyph left', !/button\.textContent = EDIT_GLYPH/.test(coreSource));
check('button renders the SVG', /button\.innerHTML = EDIT_ICON_SVG;/.test(coreSource));
// Placement: AFTER the clock, BEFORE the copy button.
check('placement helper exists', /function placeEditButton\(container, copyButton, button\)/.test(coreSource));
check(
  'inserts AFTER the copy button (right of copy)',
  /container\.insertBefore\(button, copyButton\.nextSibling\);/.test(coreSource)
);
check(
  'does not insert before copy (the old left-hand placement)',
  !/container\.insertBefore\(button, copyButton\);/.test(coreSource)
);
check('clock located by the module key names', /\S\*_time\(Start\|End\)/.test(coreSource) || /_time\(Start\|End\)/.test(coreSource));
check('falls back to after the clock', /container\.insertBefore\(button, clock\.nextSibling\);/.test(coreSource));
check('copy located by the shell copy/copied labels', /const COPY_LABELS = new Set\(\['copy', 'copied'/.test(coreSource));
// Always visible: the button sets opacity 1 and the whole action row is held open
// while it carries the host class, because the shell fades the row, not the child.
check('button opacity is 1 in the stylesheet', /\.dsh-bu-edit-btn \{[\s\S]{0,400}?opacity: 1;/.test(coreSource));
check(
  'the action row is held visible while decorated',
  /\.dsh-bu-edit-host \[class\*="_actions"\] \{\s*opacity: 1 !important;/.test(coreSource)
);
check(
  'no hover-reveal rule remains',
  !/\.dsh-bu-edit-host:hover \.dsh-bu-edit-btn/.test(coreSource)
);
// The hash may be NAMED in a comment (documenting what the shell renders) but
// must never appear as executable code — that is what would rot on a DSH rebuild.
check(
  'does not hard-code the CSS-module hash in code',
  !/qJxi1G/.test(coreWithoutComments),
  'the shell class hash must never be matched against in code'
);

check(
  'the UI states a branch session is created',
  /editNoteTitle: 'Editing a message creates a new session'/.test(core)
    && /editNoteTitle:/.test(core)
);

section('7c. the two halves speak ONE route protocol');
// The ported live-terminal browser half originally called `/api/live-terminal/*`,
// the STANDALONE plugin's namespace. The merged host half serves
// `/api/better-uiux/*`, so every live-output fetch 401'd and the UI showed nothing
// while the host captured the output perfectly. A silent, invisible mismatch.
check(
  'the client calls the merged route prefix',
  /\/api\/better-uiux\/jobs/.test(liveSource) && /\/api\/better-uiux\/output/.test(liveSource)
);
check(
  'the client never calls the standalone prefix',
  !/\/api\/live-terminal/.test(liveSource),
  'a stale route prefix makes every live-output fetch fail with 401'
);

section('8. implementation does not depend on unverified internals');
check('no raw session-log access', !/jsonl|zstd|sessionPersistence/.test(core + live));
check('no undocumented rewind/regenerate call', !/\.rewind\(|regenerate\(|editMessage\(/.test(core + live));
check('host registers a config store, not a history mutator', host.includes(`path: \`\${API}/config\``));

section('9. build inputs match the shipped bundle');
check('core.js source present', coreSource.includes('Better UIUX'));
check('live-terminal.js source present', liveSource.includes('dsh-better-uiux/live-terminal'));

// Neither part survives byte-for-byte: the live half is inlined and both are
// indented into one factory. What must hold is that every top-level DECLARATION
// from both sources is present, so nothing is silently dropped by the merge.
const declarationsOf = (source) =>
  source
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => /^(function|async function|const|let) [A-Za-z_]/.test(line));

const coreDecls = declarationsOf(coreSource);
const liveDecls = declarationsOf(liveSource);
const missingCore = coreDecls.filter((line) => !core.includes(line));
const missingLive = liveDecls.filter((line) => !core.includes(line));

check('bundle contains every core.js declaration', missingCore.length === 0, missingCore.slice(0, 3).join(' | '));
check('bundle contains every live-terminal declaration', missingLive.length === 0, missingLive.slice(0, 3).join(' | '));
check(
  'both sources contributed declarations',
  coreDecls.length > 50 && liveDecls.length > 20,
  `core=${coreDecls.length} live=${liveDecls.length}`
);

section('10. locale dictionary contract (the runtime calls template.replace)');
// Every value handed to ctx.locale.register must be a STRING. A function value
// makes LocaleRuntime.translate throw "template.replace is not a function", and
// the shell then shows a blank Settings pane. That was a real shipped bug.
const dictionaryBlocks = [...coreSource.matchAll(/\n    const (zh|en|vi) = \{([\s\S]*?)\n    \};/g)];
check('three dictionaries found', dictionaryBlocks.length === 3, `found ${dictionaryBlocks.length}`);
for (const [, locale, body] of dictionaryBlocks) {
  const entries = [...body.matchAll(/^\s{6}([A-Za-z][A-Za-z0-9_]*): (.*?),?$/gm)];
  const nonString = entries.filter(([, , value]) => !/^'[^']*'$/.test(value.trim()));
  check(`${locale}: every value is a single-quoted string`, nonString.length === 0,
    nonString.map(([, key, value]) => `${key}=${value.trim().slice(0, 40)}`).join(' | '));
}
check('translated counters use {name} placeholders', /enabledCount: '\{on\}\/\{total\} enabled'/.test(coreSource));
check('no call passes params to a non-template key', !/t\('(nav|heading|intro|editorTitle|featuresHeading|noteHeading)',\s*\{/.test(coreSource));

section('11. the section reports its own render failure instead of going blank');
check('a local error boundary wraps the section', /class SectionBoundary extends React\.Component/.test(coreSource));
check('the boundary renders the failure in the pane', /Better UIUX — render error/.test(coreSource));
check('the registered component is the guarded one', /GuardedBetterUiuxSection/.test(coreSource));
check('initialization logs a breadcrumb', /\[better-uiux\] client v\$\{CLIENT_VERSION\} initialized/.test(coreSource));

console.log(`\n${checks - failures}/${checks} checks passed`);
if (failures > 0) {
  console.error(`${failures} FAILURE(S)`);
  process.exitCode = 1;
} else {
  console.log('wiring contract ok');
}
